def romanize_word(word: str) -> str:
    """Return one display token for one transcript token."""

    normalized = unicodedata.normalize("NFC", word)
    if not _DEVANAGARI.search(normalized):
        return normalized
    try:
        return _ROMAN_TRANSLITERATIONS[normalized]
    except KeyError as exc:
        raise ValueError(
            f"Missing 0813 Roman transliteration for token: {word!r}"
        ) from exc
